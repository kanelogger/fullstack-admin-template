function spawnManaged(command, args, { cwd, env, logPath, runId }) {
  const log = createWriteStream(logPath, { flags: "a", mode: 0o600 });
  const child = spawn(command, args, {
    cwd,
    env: { ...process.env, SUPABASE_TELEMETRY_DISABLED: "1", AGENT_TEST_RUN_ID: runId, ...env },
    stdio: ["ignore", "pipe", "pipe"],
    detached: process.platform !== "win32",
    shell: process.platform === "win32",
    windowsHide: true
  });
  child.stdout?.on("data", chunk => log.write(redact(String(chunk))));
  child.stderr?.on("data", chunk => log.write(redact(String(chunk))));
  child.once("close", () => log.end());
  return child;
}

function processIsRunning(child) {
  return child.exitCode === null && child.signalCode === null;
}

async function waitForExit(child, timeoutMs) {
  if (child.closed) return true;
  return await new Promise(resolve => {
    const timer = setTimeout(() => finish(false), timeoutMs);
    const finish = result => {
      clearTimeout(timer);
      child.off("close", onClose);
      resolve(result);
    };
    const onClose = () => finish(true);
    child.once("close", onClose);
    if (child.closed) finish(true);
  });
}

function signalManagedProcess(pid, signal) {
  if (process.platform !== "win32") {
    try {
      return process.kill(-pid, signal);
    } catch (groupError) {
      if (groupError?.code !== "ESRCH") throw groupError;
      try {
        return process.kill(pid, signal);
      } catch (processError) {
        if (processError?.code === "ESRCH") return false;
        throw processError;
      }
    }
  }
  return process.kill(pid, signal);
}

async function stopChild(child, label, failures) {
  if (!child || child.closed) return;
  try {
    signalManagedProcess(child.pid, "SIGTERM");
    if (await waitForExit(child, 5_000)) return;
    signalManagedProcess(child.pid, "SIGKILL");
    if (await waitForExit(child, 2_000)) return;
    failures.push(`${label} subprocess did not exit after SIGKILL`);
  } catch (error) {
    failures.push(`${label} subprocess could not be stopped: ${error instanceof Error ? error.message : String(error)}`);
  }
}

function listeningPids(port) {
  if (!Number.isInteger(port) || port < 1 || port > 65535) return [];
  const result = spawnSync("lsof", ["-nP", `-iTCP:${port}`, "-sTCP:LISTEN", "-t"], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"]
  });
  if (result.status !== 0) return [];
  return [...new Set((result.stdout ?? "").split(/\s+/).map(Number).filter(pid => Number.isInteger(pid) && pid > 0))];
}

async function stopVerifiedPid(pid, label, expectedIdentity, ownerMarker, failures) {
  try {
    await terminateVerifiedProcess({
      pid,
      label,
      expectedIdentity,
      ownerMarkers: Array.isArray(ownerMarker) ? ownerMarker : [ownerMarker]
    }, {
      identityFor,
      signal: signalManagedProcess,
      waitForExit: (targetPid, identity, timeoutMs) => waitForIdentityChange(targetPid, identity, timeoutMs)
    });
  } catch (error) {
    failures.push(`${label} PID could not be stopped: ${error instanceof Error ? error.message : String(error)}`);
  }
}

async function waitForIdentityChange(pid, expectedIdentity, timeoutMs) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    if (identityFor(pid) !== expectedIdentity) return true;
    await new Promise(resolveDelay => setTimeout(resolveDelay, 100));
  }
  return identityFor(pid) !== expectedIdentity;
}

async function stopViteListener(record, failures) {
  const port = record.ports?.vite;
  const saved = record.children?.viteListener;
  const listenerMarkers = viteListenerOwnerMarkers(port, frontendRoot);
  const pids = new Set([...(saved?.pid ? [saved.pid] : []), ...listeningPids(port)]);
  for (const pid of pids) {
    const expected = pid === saved?.pid ? saved.identity : undefined;
    const current = identityFor(pid);
    const isOwnedVite = ownerMarkersMatch(current, listenerMarkers);
    if (expected || isOwnedVite) {
      await stopVerifiedPid(pid, "Vite listener", expected, listenerMarkers, failures);
    }
  }
  const remainingOwnedListeners = listeningPids(port)
    .map(pid => ({ pid, identity: identityFor(pid) }))
    .filter(listener => ownerMarkersMatch(listener.identity, listenerMarkers));
  for (const listener of remainingOwnedListeners) {
    failures.push(`Vite listener PID ${listener.pid} is still running after cleanup`);
  }
}

async function poll(child, label, check, timeoutMs = 30_000, lifecycle, abortSignal) {
  const deadline = Date.now() + timeoutMs;
  let last = "not ready";
  while (Date.now() < deadline) {
    lifecycle?.throwIfCancelled();
    if (abortSignal?.aborted) throw new Error(`${label} readiness check cancelled after a sibling failed`);
    if (child && !processIsRunning(child)) throw new Error(`${label} exited before becoming ready`);
    try {
      if (await check()) return;
    } catch (error) {
      last = error instanceof Error ? error.message : String(error);
    }
    await new Promise(resolveDelay => setTimeout(resolveDelay, 400));
  }
  throw new Error(`${label} did not become ready: ${last}`);
}

