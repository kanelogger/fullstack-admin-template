function identityFor(pid) {
  if (process.platform !== "darwin" && process.platform !== "linux") {
    throw new Error("Agent process recovery currently requires macOS or Linux process start identities");
  }
  const result = spawnSync("ps", ["-ww", "-p", String(pid), "-o", "stat=", "-o", "lstart=", "-o", "command="], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"]
  });
  if (result.status !== 0 || !result.stdout.trim()) return null;
  const match = result.stdout.trim().match(/^(\S+)\s+(.+)$/);
  if (!match || /^[zZ]/.test(match[1])) return null;
  return match[2].trim();
}

function safeRunId(value) {
  if (typeof value !== "string" || !/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(value)) {
    throw new Error("run-id must be a UUID generated by this command");
  }
  return value;
}

async function atomicJson(path, value) {
  const temporary = `${path}.${randomUUID()}.tmp`;
  await writeFile(temporary, `${JSON.stringify(value, null, 2)}\n`, { mode: 0o600 });
  await rename(temporary, path);
  await chmod(path, 0o600);
}

