async function persistCleanupResult(recordPath, record) {
  if (!record.evidenceStatus || record.evidenceStatus === "Pending") {
    updateEvidenceState(record, [], "Cleanup ended before evidence completeness could be determined");
  }
  enforceEvidenceGate(record);
  record.cleanupFailures = [...new Set(record.cleanupFailures ?? [])];
  record.cleanupStatus = record.cleanupFailures.length ? "Failed" : "Succeeded";
  record.finishedAt ??= new Date().toISOString();
  try {
    await atomicJson(recordPath, record);
  } catch (error) {
    record.cleanupFailures.push(`Run state write: ${error instanceof Error ? error.message : String(error)}`);
    record.cleanupStatus = "Failed";
  }
  try {
    await publishReport(record);
  } catch (error) {
    record.cleanupFailures.push(`Report write: ${error instanceof Error ? error.message : String(error)}`);
    record.cleanupStatus = "Failed";
    await atomicJson(recordPath, record).catch(() => undefined);
  }
  return record.cleanupStatus;
}

async function cleanup(args) {
  const options = parseArgs(args);
  const runId = safeRunId(options["--run-id"]);
  const requestedStatus = options["--product-status"];
  if (options["--browser-page-visited"] !== undefined && options["--browser-page-visited"] !== "true") {
    throw new Error("--browser-page-visited accepts only true when the app page was inspected");
  }
  if (requestedStatus && !["Pass", "Fail", "Unknown"].includes(requestedStatus)) {
    throw new Error("--product-status must be Pass, Fail, or Unknown");
  }

  const { recordPath, record } = await readRun(runId);
  if (options["--browser-page-visited"] === "true") record.browserPageVisited = true;
  const previousStatus = record.productStatus;
  record.productStatus = mergeProductStatus(previousStatus, requestedStatus);
  if (options["--reason"] && !(previousStatus === "Fail" && requestedStatus !== "Fail")) {
    record.productReason = options["--reason"];
  }
  await atomicJson(recordPath, record);

  const supervisorIdentity = record.supervisor?.identity;
  const currentIdentity = record.supervisor?.pid ? identityFor(record.supervisor.pid) : null;
  const supervisorMode = supervisorCleanupMode(supervisorIdentity, currentIdentity, record.finishedAt);

  if (supervisorMode === "wait") {
    const exited = await waitForIdentityChange(record.supervisor.pid, supervisorIdentity, 30_000);
    if (!exited) {
      record.cleanupFailures = [
        ...(record.cleanupFailures ?? []),
        "Completed Dashboard supervisor did not exit; orphan cleanup was deferred to avoid racing it"
      ];
      await persistCleanupResult(recordPath, record);
      throw new Error(`Supervisor did not exit for run ${runId}`);
    }
  } else if (supervisorMode === "signal") {
    if (!currentIdentity.includes("scripts/agent-testing.mjs start")) {
      throw new Error("Recorded supervisor command did not match this test runner");
    }
    try {
      signalManagedProcess(record.supervisor.pid, "SIGTERM");
    } catch (error) {
      if (identityFor(record.supervisor.pid) === supervisorIdentity) throw error;
    }
    const exited = await waitForIdentityChange(record.supervisor.pid, supervisorIdentity, 180_000);
    if (!exited) {
      record.cleanupFailures = [
        ...(record.cleanupFailures ?? []),
        "Dashboard supervisor did not exit after SIGTERM; no orphan cleanup was run concurrently"
      ];
      await persistCleanupResult(recordPath, record);
      throw new Error(`Supervisor did not exit for run ${runId}`);
    }
  }

  const latest = await readRun(runId);
  const finalRecord = latest.record;
  await stopOrphan(finalRecord);
  const cleanupStatus = await persistCleanupResult(latest.recordPath, finalRecord);
  console.log(JSON.stringify({
    runId,
    productStatus: finalRecord.productStatus ?? "Unknown",
    cleanupStatus,
    reportPath: reportPath(runId),
    retainedProjectRoot: finalRecord.retainedProjectRoot ?? null
  }));
  if (cleanupStatus !== "Succeeded") throw new Error(`Cleanup failed for run ${runId}`);
}

async function stopOrphan(record) {
  return await cleanupOwnedRun(record, { vite: undefined, edge: undefined });
}

async function fillCredential(args) {
  const options = parseArgs(args);
  const { root, record } = await readRun(safeRunId(options["--run-id"]));
  const field = options["--field"];
  const sessionId = options["--session"];
  const reference = options["--ref"];
  if (!sessionId || !reference || !["loginName", "password"].includes(field)) {
    throw new Error("Usage: node scripts/agent-testing.mjs fill --run-id <id> --session <id> --ref <element-ref> --field loginName|password");
  }
  if (sessionId !== record.browser?.sessionId) throw new Error("BrowserSkill Session does not belong to this run");
  const credentials = JSON.parse(await readFile(join(root, "credentials.json"), "utf8"));
  const value = credentials[field];
  if (typeof value !== "string" || !value) throw new Error("Requested temporary credential is unavailable");
  runSync("bsk", ["fill", reference, "--value", value, "--session", sessionId], {
    timeout: 20_000,
    env: { BSK_AUTO_START: "0" }
  });
}

async function main() {
  const [command, ...args] = process.argv.slice(2);
  if (command === "start") return await start(args);
  if (command === "cleanup") return await cleanup(args);
  if (command === "fill") return await fillCredential(args);
  throw new Error("Usage: node scripts/agent-testing.mjs <start|cleanup|fill> ...");
}

const invokedPath = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : "";
if (invokedPath === import.meta.url) {
  main().catch(error => {
    process.stderr.write(`${redact(error instanceof Error ? error.stack ?? error.message : String(error))}\n`);
    process.exitCode = 1;
  });
}
