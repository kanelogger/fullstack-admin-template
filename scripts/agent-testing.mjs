async function verifySavedEvidence(record, evidenceDirectory, unknownReason, evidenceFailures, operations = {}) {
  const statFile = operations.stat ?? stat;
  const readFileContent = operations.readFile ?? readFile;
  const debugArtifact = "evidence/browser-debug.json";
  if (!(record.requiredEvidence ?? []).includes(debugArtifact)) {
    try {
      const debugFile = await statFile(join(evidenceDirectory, "browser-debug.json"));
      if (debugFile.isFile() && debugFile.size > 0) addRequiredEvidence(record, debugArtifact);
    } catch (error) {
      if (error?.code !== "ENOENT") {
        unknownReason ??= `Could not inspect saved BrowserSkill debug evidence: ${error instanceof Error ? error.message : String(error)}`;
      }
    }
  }
  const present = [];
  const invalidArtifacts = [];
  let verificationFailure = unknownReason;
  for (const evidencePath of record.requiredEvidence ?? []) {
    const fullPath = join(reportsRoot, record.runId, ...evidencePath.split("/"));
    try {
      const file = await statFile(fullPath);
      if (!file.isFile() || file.size === 0) continue;
      if (evidencePath.endsWith(".json")) {
        const document = JSON.parse(await readFileContent(fullPath, "utf8"));
        if (!document || typeof document !== "object" || !(document.run || Array.isArray(document.runs))) {
          invalidArtifacts.push(`Saved debug evidence has an invalid document: ${evidencePath}`);
          continue;
        }
      } else if (evidencePath.endsWith(".png")) {
        const image = await readFileContent(fullPath);
        if (!image.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]))) {
          invalidArtifacts.push(`Saved screenshot has an invalid PNG signature: ${evidencePath}`);
          continue;
        }
      }
      present.push(evidencePath);
    } catch (error) {
      if (error?.code === "ENOENT") continue;
      if (error instanceof SyntaxError) {
        invalidArtifacts.push(`Saved debug evidence is not valid JSON: ${evidencePath}`);
      } else {
        verificationFailure ??= `Could not verify ${evidencePath}: ${error instanceof Error ? error.message : String(error)}`;
      }
    }
  }
  updateEvidenceState(record, present, verificationFailure, [...evidenceFailures, ...invalidArtifacts]);
}

export async function bestEffortBrowserCleanup(record, cleanupFailures = [], operations = {}) {
  const run = operations.runSync ?? runSync;
  const makeDirectory = operations.mkdir ?? mkdir;
  const writeRecord = operations.atomicJson ?? atomicJson;
  const stopSession = operations.stopBrowserSession ?? stopBrowserSession;
  const evidenceFailures = [];
  const sessionId = record.browser?.sessionId;
  const evidenceDirectory = join(reportsRoot, record.runId, "evidence");
  if (record.browserPageVisited) addRequiredEvidence(record, "evidence/dashboard-final.png");
  if (!sessionId) {
    const unknownReason = record.browserPageVisited
      ? "BrowserSkill session is unavailable before required evidence could be collected"
      : null;
    await verifySavedEvidence(record, evidenceDirectory, unknownReason, evidenceFailures, operations);
    return;
  }

  let present = true;
  let evidenceUnknownReason;
  try {
    present = browserSessionPresent(record, run);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    cleanupFailures.push(`BrowserSkill session ownership check: ${message}`);
    evidenceUnknownReason = `BrowserSkill session ownership could not be verified: ${message}`;
    if (error?.code === "BSK_INSTANCE_MISMATCH") {
      await verifySavedEvidence(record, evidenceDirectory, evidenceUnknownReason, evidenceFailures, operations);
      return;
    }
  }
  if (!present) {
    if ((!record.evidenceStatus || record.evidenceStatus === "Pending") && record.browserPageVisited) {
      const debugArtifact = join(evidenceDirectory, "browser-debug.json");
      const debugExists = await stat(debugArtifact).then(file => file.isFile() && file.size > 0).catch(() => false);
      if (!debugExists) evidenceUnknownReason = "BrowserSkill session ended before capture status could be checked";
    }
    await verifySavedEvidence(record, evidenceDirectory, evidenceUnknownReason, evidenceFailures, operations);
    return;
  }

  if (record.browserPageVisited) {
    try {
      await makeDirectory(evidenceDirectory, { recursive: true });
      const screenshot = join(evidenceDirectory, "dashboard-final.png");
      run("bsk", ["screenshot", "--session", sessionId, "--full-page", "--out", screenshot], { timeout: 30_000 });
    } catch (error) {
      evidenceFailures.push(`BrowserSkill screenshot: ${error instanceof Error ? error.message : String(error)}`);
    }
  }

  try {
    const status = parseJson(run("bsk", ["debug", "status", "--session", sessionId], {
      timeout: 15_000,
      env: { BSK_AUTO_START: "0" }
    }), "BrowserSkill debug status");
    const captureFound = hasBrowserDebugCapture(status);
    if (captureFound) {
      addRequiredEvidence(record, "evidence/browser-debug.json");
      try {
        await writeRecord(join(record.stateRoot, "run.json"), record);
      } catch (error) {
        evidenceFailures.push(`Could not persist required BrowserSkill debug evidence: ${error instanceof Error ? error.message : String(error)}`);
        evidenceUnknownReason = "The required BrowserSkill debug evidence marker could not be persisted";
      }
    }
    if (captureFound) {
      let captureStopped = !isDebugCaptureActive(status);
      if (isDebugCaptureActive(status)) {
        try {
          run("bsk", ["debug", "stop", "--session", sessionId], { timeout: 20_000, env: { BSK_AUTO_START: "0" } });
          const stoppedStatus = parseJson(run("bsk", ["debug", "status", "--session", sessionId], {
            timeout: 15_000,
            env: { BSK_AUTO_START: "0" }
          }), "BrowserSkill debug status after stop");
          captureStopped = !isDebugCaptureActive(stoppedStatus);
          if (!captureStopped) evidenceFailures.push("BrowserSkill debug capture remained active after stop");
        } catch (error) {
          evidenceFailures.push(`BrowserSkill debug stop: ${error instanceof Error ? error.message : String(error)}`);
        }
      }
      if (captureStopped) {
        try {
          await makeDirectory(evidenceDirectory, { recursive: true });
          const exportPath = join(evidenceDirectory, "browser-debug.json");
          run("bsk", ["debug", "export", "--session", sessionId, "--output", exportPath], {
            timeout: 30_000,
            env: { BSK_AUTO_START: "0" }
          });
        } catch (error) {
          evidenceFailures.push(`BrowserSkill debug export: ${error instanceof Error ? error.message : String(error)}`);
        }
      }
    }
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    evidenceUnknownReason = `BrowserSkill debug status could not be inspected: ${message}`;
    evidenceFailures.push(`BrowserSkill debug status: ${message}`);
  }

  try {
    stopSession(sessionId);
  } catch (error) {
    try {
      if (browserSessionPresent(record, run)) {
        cleanupFailures.push(`BrowserSkill session stop: ${error instanceof Error ? error.message : String(error)}`);
      }
    } catch (stateError) {
      cleanupFailures.push(`BrowserSkill session stop: ${error instanceof Error ? error.message : String(error)}; verification failed: ${stateError instanceof Error ? stateError.message : String(stateError)}`);
    }
  }

  await verifySavedEvidence(record, evidenceDirectory, evidenceUnknownReason, evidenceFailures, operations);
}

async function stopRecordedProcess(liveChild, recordedChild, label, failures) {
  if (liveChild && !liveChild.closed) {
    await stopChild(liveChild, label, failures);
    return;
  }
  if (!recordedChild?.pid) return;
  await stopVerifiedPid(
    recordedChild.pid,
    label,
    recordedChild.identity,
    recordedChild.ownerMarker,
    failures
  );
}

async function stopRecordedChildren(record, children, failures) {
  await stopRecordedProcess(children.vite, record.children?.vite, "Vite", failures);
  await stopViteListener(record, failures);
  await stopRecordedProcess(children.edge, record.children?.edge, "Edge Functions", failures);
}

async function cleanupOwnedRun(record, children) {
  const result = await cleanupOwnedResources(record, {
    cleanupBrowser: async () => {
      const failures = [];
      await bestEffortBrowserCleanup(record, failures);
      return failures;
    },
    stopProcesses: async () => {
      const failures = [];
      await stopRecordedChildren(record, children, failures);
      return failures;
    },
    stopStack: async () => {
      const expected = join(record.tempRoot, "project");
      if (
        !record.projectRoot || record.projectRoot !== expected ||
        !record.projectId?.startsWith("agent-dashboard-")
      ) {
        throw new Error("Temporary project ownership did not match the recorded run");
      }
      projectCli(record.projectRoot, ["stop", "--project-id", record.projectId, "--no-backup"], { timeout: 90_000 });
    },
    removeProject: async () => {
      if (!record.tempRoot && !record.projectRoot) return;
      if (!record.tempRoot || record.projectRoot !== join(record.tempRoot, "project")) {
        throw new Error("Temporary project directory ownership did not match the recorded run");
      }
      await rm(record.tempRoot, { recursive: true, force: true });
    },
    removeCredentials: async () => {
      if (record.stateRoot) await rm(join(record.stateRoot, "credentials.json"), { force: true });
    }
  });
  if (!record.evidenceStatus || record.evidenceStatus === "Pending") {
    updateEvidenceState(record, [], "Evidence collection did not complete");
  }
  enforceEvidenceGate(record);
  return result;
}

async function shutdown(recordPath, record, children, reason) {
  if (record.shutdownPromise) return record.shutdownPromise;
  record.shutdownPromise = (async () => {
    record.shutdownReason ??= reason;
    try {
      const latest = JSON.parse(await readFile(recordPath, "utf8"));
      if (latest.productStatus === "Fail") {
        record.productStatus = "Fail";
        record.productReason = latest.productReason ?? record.productReason;
      } else {
        record.productStatus = mergeProductStatus(record.productStatus, latest.productStatus);
        if (record.productStatus !== "Fail" && latest.productReason) record.productReason = latest.productReason;
      }
      record.browserPageVisited = mergeBrowserPageVisited(record.browserPageVisited, latest.browserPageVisited);
      record.evidence = [...new Set([...(record.evidence ?? []), ...(latest.evidence ?? [])])];
    } catch (error) {
      record.cleanupFailures = [
        ...(record.cleanupFailures ?? []),
        `Run state reload: ${error instanceof Error ? error.message : String(error)}`
      ];
      record.productStatus ??= "Unknown";
    }

    try {
      await cleanupOwnedRun(record, children);
    } catch (error) {
      record.cleanupFailures = [
        ...(record.cleanupFailures ?? []),
        `Cleanup orchestration: ${error instanceof Error ? error.message : String(error)}`
      ];
    }
    if (!record.evidenceStatus || record.evidenceStatus === "Pending") {
      updateEvidenceState(record, [], "Cleanup ended before evidence completeness could be determined");
    }
    enforceEvidenceGate(record);
    record.cleanupFailures = [...new Set(record.cleanupFailures ?? [])];
    record.cleanupStatus = record.cleanupFailures.length ? "Failed" : "Succeeded";
    record.finishedAt = new Date().toISOString();
    try {
      await atomicJson(recordPath, record);
    } catch (error) {
      record.cleanupFailures.push(`Run state write: ${error instanceof Error ? error.message : String(error)}`);
      record.cleanupStatus = "Failed";
    }
    try {
      await publishReport(record);
    } catch (error) {
      record.cleanupFailures.push(`Report write: ${error instanceof Error ? error.message : String(error)}`);
      record.cleanupStatus = "Failed";
      await atomicJson(recordPath, record).catch(() => undefined);
    }
    process.exitCode = record.cleanupStatus === "Succeeded" ? 0 : 1;
  })();
  return record.shutdownPromise;
}

