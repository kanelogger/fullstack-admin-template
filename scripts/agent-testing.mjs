function redact(text) {
  return text
    .replace(/(service[_ -]?role[_ -]?key|secret[_ -]?key)(\s*[:=]\s*)[^\s"']+/gi, "$1$2[REDACTED]")
    .replace(/\bsb_secret_[a-zA-Z0-9_-]+/g, "[REDACTED]")
    .replace(/\beyJ[a-zA-Z0-9_.-]{24,}/g, "[REDACTED]")
    .replace(/(postgres(?:ql)?:\/\/[^:/\s]+:)[^@\s]+@/gi, "$1[REDACTED]@");
}

function runSync(command, args, options = {}) {
  const result = spawnSync(command, args, {
    cwd: options.cwd ?? projectRoot,
    encoding: "utf8",
    timeout: options.timeout ?? 180_000,
    stdio: ["ignore", "pipe", "pipe"],
    env: { ...process.env, SUPABASE_TELEMETRY_DISABLED: "1", ...options.env },
    shell: process.platform === "win32"
  });
  if (result.error || result.status !== 0) {
    const output = redact(`${result.stdout ?? ""}\n${result.stderr ?? ""}`).trim();
    throw new Error(`${command} failed (${result.error?.message ?? `exit code ${result.status ?? 1}`})${output ? `\n${output.slice(-2600)}` : ""}`);
  }
  return result.stdout ?? "";
}

