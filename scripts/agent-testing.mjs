function browserSessionPresent(record, run = runSync) {
  const sessions = parseJson(run("bsk", ["session", "list", "--json"], {
    timeout: 10_000,
    env: { BSK_AUTO_START: "0" }
  }), "BrowserSkill session list");
  const session = sessions.find(item => item.session_id === record.browser?.sessionId);
  if (!session) return false;
  if (session.browser_instance_id !== record.browser?.instanceId) {
    const error = new Error("BrowserSkill session is attached to a different instance than this run");
    error.code = "BSK_INSTANCE_MISMATCH";
    throw error;
  }
  return true;
}

function preflightBrowser(browserId) {
  const status = parseJson(runSync("bsk", ["status", "--json"], {
    timeout: 10_000,
    env: { BSK_AUTO_START: "0" }
  }), "BrowserSkill status");
  const browser = status.browsers?.find(instance => instance.instance_id === browserId);
  if (!browser || browser.unresponsive) throw new Error(`BrowserSkill instance ${browserId} is not connected and responsive`);

  const listed = parseJson(runSync("bsk", ["browsers", "--json"], {
    timeout: 10_000,
    env: { BSK_AUTO_START: "0" }
  }), "BrowserSkill browser list");
  if (!listed.some(instance => instance.instance_id === browserId && !instance.unresponsive)) {
    throw new Error(`BrowserSkill instance ${browserId} is not available`);
  }

  const session = parseJson(runSync("bsk", ["session", "start", "--browser", browserId, "--json"], {
    timeout: 20_000,
    env: { BSK_AUTO_START: "0" }
  }), "BrowserSkill session start");
  if (session.browser_instance_id !== browserId || typeof session.session_id !== "string") {
    if (typeof session.session_id === "string") stopBrowserSession(session.session_id);
    throw new Error("BrowserSkill started a session on an unexpected browser instance");
  }

  try {
    const capabilities = parseJson(runSync("bsk", ["debug", "capabilities", "--session", session.session_id], {
      timeout: 20_000,
      env: { BSK_AUTO_START: "0" }
    }), "BrowserSkill debug capability check");
    const actions = capabilities.capabilities?.actions ?? [];
    for (const required of ["start", "stop", "status", "export"]) {
      if (!actions.includes(required)) throw new Error(`BrowserSkill debug capability ${required} is unavailable`);
    }
    return {
      browserId,
      sessionId: session.session_id,
      daemonVersion: status.daemon_version ?? null,
      browserVersion: browser.browser_version ?? null,
      extensionVersion: browser.extension_version ?? null
    };
  } catch (error) {
    try { stopBrowserSession(session.session_id); } catch { /* preserve the original preflight failure */ }
    throw error;
  }
}

