async function waitForEdge(child, apiUrl, publishableKey, origin, lifecycle, abortSignal) {
  let postAllowOrigin;
  await poll(child, "Edge Functions", async () => {
    const response = await fetch(`${apiUrl}/functions/v1/session-login`, {
      method: "POST",
      headers: { apikey: publishableKey, "content-type": "application/json", Origin: origin },
      body: JSON.stringify({ loginName: "__agent_readiness_probe__", password: "invalid-readiness-password" }),
      signal: AbortSignal.timeout(2_000)
    });
    const data = await response.json().catch(() => null);
    if (response.status !== 401 || data?.error?.code !== "INVALID_CREDENTIALS") return false;
    postAllowOrigin = response.headers.get("access-control-allow-origin");
    return true;
  }, 30_000, lifecycle, abortSignal);
  if (abortSignal?.aborted) throw new Error("Edge readiness check cancelled after a sibling failed");
  if (postAllowOrigin !== origin && postAllowOrigin !== "*") {
    throw new Error(`session-login CORS rejected the allowed origin (Access-Control-Allow-Origin: ${postAllowOrigin ?? "<missing>"})`);
  }

  const response = await fetch(`${apiUrl}/functions/v1/session-login`, {
    method: "OPTIONS",
    headers: {
      Origin: origin,
      "access-control-request-method": "POST",
      "access-control-request-headers": "apikey,authorization,content-type"
    },
    signal: AbortSignal.timeout(3_000)
  });
  const allowedOrigin = response.headers.get("access-control-allow-origin");
  if (!response.ok || (allowedOrigin !== origin && allowedOrigin !== "*")) {
    throw new Error(`Edge Function OPTIONS CORS denied the selected Vite origin (status ${response.status}, Access-Control-Allow-Origin: ${allowedOrigin ?? "<missing>"})`);
  }
  const allowedHeaders = response.headers.get("access-control-allow-headers")?.toLowerCase() ?? "";
  for (const header of ["apikey", "authorization", "content-type"]) {
    if (!allowedHeaders.includes(header)) throw new Error(`Edge Function CORS did not allow ${header}`);
  }
}

