create table public.dict_types (
  id bigint generated by default as identity primary key,
  dict_code varchar(64) not null,
  dict_name varchar(128) not null check (length(trim(dict_name)) between 1 and 128),
  status smallint not null default 1 check (status in (0, 1)),
  description varchar(255),
  created_by bigint references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_by bigint references public.profiles (id) on delete set null,
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  constraint dict_types_code_not_blank check (length(trim(dict_code)) between 1 and 64)
);

create table public.dict_items (
  id bigint generated by default as identity primary key,
  dict_type_id bigint not null references public.dict_types (id) on delete restrict,
  item_value varchar(64) not null check (length(trim(item_value)) between 1 and 64),
  item_label varchar(128) not null check (length(trim(item_label)) between 1 and 128),
  sort_order integer not null default 0,
  status smallint not null default 1 check (status in (0, 1)),
  description varchar(255),
  created_by bigint references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_by bigint references public.profiles (id) on delete set null,
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

create table public.system_configs (
  id bigint generated by default as identity primary key,
  config_code varchar(64) not null,
  config_name varchar(128) not null check (length(trim(config_name)) between 1 and 128),
  config_value text not null,
  value_type varchar(32) not null default 'STRING'
    check (value_type in ('STRING', 'NUMBER', 'BOOLEAN', 'JSON')),
  status smallint not null default 1 check (status in (0, 1)),
  description varchar(255),
  created_by bigint references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_by bigint references public.profiles (id) on delete set null,
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  constraint system_configs_code_not_blank check (length(trim(config_code)) between 1 and 64)
);

