-- Dictionary and system configuration tables retain legacy behavior while
-- keeping BIGINT values text-only at the browser RPC boundary.

-- MySQL's utf8mb4_unicode_ci was case-insensitive for these business keys.
-- ICU primary-strength comparison ignores both case and accents, closely
-- matching that legacy uniqueness contract.
create collation if not exists app_private.legacy_utf8mb4_unicode_ci (
  provider = icu,
  locale = 'und-u-ks-level1',
  deterministic = false
);

