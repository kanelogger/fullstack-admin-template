-- Legacy imports are intentionally service-role-only. Both preview and apply
-- validate the full source batch; apply preserves source BIGINT IDs and time.
create function public.import_legacy_departments(p_rows jsonb, p_apply boolean)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  source_count integer;
  distinct_id_count integer;
  already_present_count integer;
  rows_to_insert integer;
  inserted_count integer := 0;
  maximum_department_id bigint;
  imported_department record;
  existing_department public.departments%rowtype;
begin
  if p_apply is null or jsonb_typeof(p_rows) is distinct from 'array' then
    raise exception using errcode = '22023', message = 'Department import input is invalid';
  end if;
  source_count := jsonb_array_length(p_rows);
  if source_count > 100 then
    raise exception using errcode = '22023', message = 'Department import batches cannot exceed 100 rows';
  end if;
  if exists (
    select 1
    from jsonb_to_recordset(p_rows) as source(
      id text, dept_code text, dept_name text, status integer,
      description text, deleted boolean, created_at timestamptz, updated_at timestamptz
    )
    where coalesce(source.id, '') !~ '^[1-9][0-9]*$'
       or source.dept_code is null
       or source.dept_name is null
       or source.status is null
       or source.status not in (0, 1)
       or source.deleted is null
       or source.created_at is null
       or source.updated_at is null
       or source.dept_code <> btrim(source.dept_code)
       or source.dept_name <> btrim(source.dept_name)
       or length(source.dept_code) not between 1 and 64
       or length(source.dept_name) not between 1 and 128
       or coalesce(length(source.description), 0) > 255
  ) then
    raise exception using errcode = '22023', message = 'Department import contains invalid fields';
  end if;
  if exists (
    select 1
    from jsonb_to_recordset(p_rows) as source(id text, dept_code text)
    where source.id::numeric > 9223372036854775807
  ) then
    raise exception using errcode = '22003', message = 'Department ID exceeds PostgreSQL BIGINT range';
  end if;

  select count(distinct source.id)::integer into distinct_id_count
  from jsonb_to_recordset(p_rows) as source(id text);
  if distinct_id_count <> source_count then
    raise exception using errcode = '23505', message = 'Department import contains duplicate IDs';
  end if;
  if exists (
    select lower(btrim(source.dept_code))
    from jsonb_to_recordset(p_rows) as source(dept_code text)
    group by lower(btrim(source.dept_code))
    having count(*) > 1
  ) then
    raise exception using errcode = '23505', message = 'Department import contains duplicate codes';
  end if;

  for imported_department in
    select * from jsonb_to_recordset(p_rows) as source(
      id text, dept_code text, dept_name text, status integer,
      description text, deleted boolean, created_at timestamptz, updated_at timestamptz
    )
  loop
    select * into existing_department
    from public.departments as department
    where department.id = imported_department.id::bigint;
    if found then
      if existing_department.dept_code is distinct from imported_department.dept_code
        or existing_department.dept_name is distinct from imported_department.dept_name
        or existing_department.status is distinct from imported_department.status::smallint
        or existing_department.description is distinct from imported_department.description
        or existing_department.deleted is distinct from imported_department.deleted
        or existing_department.created_at is distinct from imported_department.created_at
        or existing_department.updated_at is distinct from imported_department.updated_at then
        raise exception using errcode = '23505', message = 'Department import conflicts with an existing ID';
      end if;
    end if;
  end loop;

  select count(*)::integer into already_present_count
  from jsonb_to_recordset(p_rows) as source(id text)
  join public.departments as department on department.id = source.id::bigint;
  rows_to_insert := source_count - already_present_count;

  if exists (
    select 1
    from jsonb_to_recordset(p_rows) as source(id text, dept_code text)
    join public.departments as department
      on lower(department.dept_code) = lower(btrim(source.dept_code))
     and department.id <> source.id::bigint
  ) then
    raise exception using errcode = '23505', message = 'Department code conflicts with another ID';
  end if;

  if p_apply then
    if rows_to_insert > 0 then
      insert into public.departments (
        id, dept_code, dept_name, status, description, deleted, created_at, updated_at
      )
      select source.id::bigint, source.dept_code, source.dept_name,
        source.status::smallint, source.description, source.deleted,
        source.created_at, source.updated_at
      from jsonb_to_recordset(p_rows) as source(
        id text, dept_code text, dept_name text, status integer,
        description text, deleted boolean, created_at timestamptz, updated_at timestamptz
      )
      where not exists (
        select 1 from public.departments as existing
        where existing.id = source.id::bigint
      );
      get diagnostics inserted_count = row_count;
    end if;
    select max(id) into maximum_department_id from public.departments;
    if maximum_department_id is not null then
      perform setval(
        pg_get_serial_sequence('public.departments', 'id'),
        maximum_department_id,
        true
      );
    end if;
  end if;

  return jsonb_build_object(
    'sourceCount', source_count,
    'alreadyPresentCount', already_present_count,
    'rowsToInsert', rows_to_insert,
    'insertedCount', inserted_count
  );
end;
$$;

