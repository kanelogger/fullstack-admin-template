-- Preflight profile backfills without returning BIGINT values through the
-- browser-facing Data API. Deleted directory rows still count as valid legacy
-- references because profiles retain their original department/post IDs.
create function public.assert_legacy_organization_references(
  p_department_ids text[],
  p_post_ids text[]
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  organization_id text;
begin
  if cardinality(coalesce(p_department_ids, array[]::text[])) > 100
    or cardinality(coalesce(p_post_ids, array[]::text[])) > 100 then
    raise exception using errcode = '22023', message = 'Organization reference batches cannot exceed 100 IDs';
  end if;

  foreach organization_id in array coalesce(p_department_ids, array[]::text[]) loop
    if organization_id is null or organization_id !~ '^[1-9][0-9]*$' then
      raise exception using errcode = '22023', message = 'Department reference ID is invalid';
    end if;
    if organization_id::numeric > 9223372036854775807 then
      raise exception using errcode = '22003', message = 'Department reference ID exceeds PostgreSQL BIGINT range';
    end if;
    perform 1 from public.departments as department
    where department.id = organization_id::bigint;
    if not found then
      raise exception using errcode = '23503', message = 'A legacy profile references a missing department';
    end if;
  end loop;

  foreach organization_id in array coalesce(p_post_ids, array[]::text[]) loop
    if organization_id is null or organization_id !~ '^[1-9][0-9]*$' then
      raise exception using errcode = '22023', message = 'Post reference ID is invalid';
    end if;
    if organization_id::numeric > 9223372036854775807 then
      raise exception using errcode = '22003', message = 'Post reference ID exceeds PostgreSQL BIGINT range';
    end if;
    perform 1 from public.posts as post
    where post.id = organization_id::bigint;
    if not found then
      raise exception using errcode = '23503', message = 'A legacy profile references a missing post';
    end if;
  end loop;
end;
$$;

revoke all on function public.assert_legacy_organization_references(text[], text[])
  from public, anon, authenticated;
grant execute on function public.assert_legacy_organization_references(text[], text[])
  to service_role;
