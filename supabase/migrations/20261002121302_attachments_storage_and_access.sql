create table public.attachments (
  id bigint generated by default as identity primary key,
  original_name text not null check (
    length(trim(original_name)) between 1 and 255
    and original_name !~ '[[:cntrl:]]'
  ),
  storage_path text not null unique check (length(storage_path) <= 512),
  mime_type text not null check (length(mime_type) between 1 and 128),
  file_ext text not null check (length(file_ext) between 1 and 32),
  file_size bigint not null check (file_size between 0 and 20971520),
  business_module text,
  business_record_id bigint,
  reference_status smallint not null default 0 check (reference_status in (0, 1)),
  upload_user_id bigint not null references public.profiles (id) on delete restrict,
  uploaded_at timestamptz not null default now(),
  created_by bigint references public.profiles (id) on delete set null,
  updated_by bigint references public.profiles (id) on delete set null,
  deleted_at timestamptz,
  constraint attachments_business_reference_pair check (
    (business_module is null and business_record_id is null)
    or (nullif(trim(business_module), '') is not null and business_record_id > 0)
  ),
  constraint attachments_reference_status_matches_link check (
    reference_status = case when business_module is null then 0 else 1 end
  )
);

create index attachments_active_uploaded_idx
  on public.attachments (uploaded_at desc, id desc)
  where deleted_at is null;
create index attachments_business_active_idx
  on public.attachments (business_module, business_record_id, uploaded_at desc)
  where deleted_at is null;
create index attachments_uploader_uploaded_idx
  on public.attachments (upload_user_id, uploaded_at desc)
  where deleted_at is null;

